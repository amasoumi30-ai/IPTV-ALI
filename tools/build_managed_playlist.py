#!/usr/bin/env python3
"""Create an IPTV-ALI full playlist while retaining all unverified channels.

Input 1:  original M3U used in Jellyfin (68 channels).
Input 2:  verified M3U generated by iptv_ali_maintainer.py.
Output:   separate managed M3U, never overwrites either input.
"""
from collections import defaultdict
from pathlib import Path
import os
import tempfile

ROOT = Path("/opt/iptv/playlists")
SOURCE = ROOT / "IPTV-ALI-PERSIAN-TEST.m3u"
VERIFIED = ROOT / "IPTV-ALI-VERIFIED.m3u"
OUTPUT = ROOT / "IPTV-ALI-MANAGED.m3u"


def read_playlist(path):
    lines = path.read_text(encoding="utf-8-sig", errors="replace").splitlines()
    heading, records, current = [], [], None
    for line in lines:
        if line.lstrip().startswith("#EXTINF"):
            current = {"lines": [line], "meta": line.strip(), "url": None, "url_index": None}
            records.append(current)
        elif current is None:
            heading.append(line)
        else:
            current["lines"].append(line)
            if current["url"] is None and line.strip() and not line.lstrip().startswith("#"):
                current["url"] = line.strip()
                current["url_index"] = len(current["lines"]) - 1
    if not records or any(item["url"] is None for item in records):
        raise ValueError("M3U invalid or a stream URL is missing in " + str(path))
    return heading, records


def main():
    if not SOURCE.is_file() or not VERIFIED.is_file():
        raise SystemExit("Required source/verified file not found; nothing modified")
    header, original = read_playlist(SOURCE)
    _, confirmed = read_playlist(VERIFIED)
    if len(confirmed) > len(original):
        raise SystemExit("Verified playlist has too many entries; no changes made")

    # Match exact source URLs first. This matters for duplicate channel names
    # (e.g. two PMCs): only update the duplicate whose URL was replaced.
    consumed = set()
    exact_index = defaultdict(list)
    for j, item in enumerate(confirmed):
        exact_index[(item["meta"], item["url"])].append(j)

    matched = {}
    for i, item in enumerate(original):
        options = exact_index[(item["meta"], item["url"])]
        while options and options[0] in consumed:
            options.pop(0)
        if options:
            j = options.pop(0)
            consumed.add(j)
            matched[i] = j

    # Only unmatched original entries can receive replacement URLs.
    remaining = defaultdict(list)
    for j, item in enumerate(confirmed):
        if j not in consumed:
            remaining[item["meta"]].append(j)
    changes = []
    for i, item in enumerate(original):
        if i in matched:
            continue
        options = remaining[item["meta"]]
        if not options:
            continue
        j = options.pop(0)
        matched[i] = j
        replacement = confirmed[j]["url"]
        if replacement != item["url"]:
            item["lines"][item["url_index"]] = replacement
            changes.append((i + 1, item["meta"].rsplit(",", 1)[-1]))

    if len(matched) != len(confirmed):
        raise SystemExit("Not all verified streams matched originals; no changes made")
    if OUTPUT.resolve() in (SOURCE.resolve(), VERIFIED.resolve()):
        raise SystemExit("Output conflicts with an input; refusing overwrite")

    # Keep original metadata and every channel including those still marked FAIL.
    output = "\n".join(header + [line for item in original for line in item["lines"]]) + "\n"
    fd, temp_name = tempfile.mkstemp(prefix=".IPTV-ALI-MANAGED.", dir=ROOT)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(output)
        os.chmod(temp_name, 0o644)
        os.replace(temp_name, OUTPUT)
    finally:
        if os.path.exists(temp_name):
            os.unlink(temp_name)

    print("ORIGINAL CHANNELS:", len(original))
    print("VERIFIED STREAM ENTRIES MATCHED:", len(matched))
    print("REPLACEMENTS APPLIED:", len(changes))
    for number, name in changes:
        print("  Updated channel", number, "-", name)
    print("UNVERIFIED CHANNELS RETAINED:", len(original) - len(matched))
    print("NEW FILE:", OUTPUT)
    print("JELLYFIN TUNER: unchanged")
    print("ORIGINAL PLAYLIST: unchanged")
    print("BACKUP: unchanged")
    print("NOTE: A verified URL worked at test time; no guarantee of future uptime.")


if __name__ == "__main__":
    main()
